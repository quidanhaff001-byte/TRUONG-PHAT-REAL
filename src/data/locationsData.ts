/**
 * Quick search helper matching both new name, former district/city, and aliases
 */
export function findLocationByQuery(query: string, locations: LocationItem[] = MASTER_LOCATIONS): LocationItem[] {
  if (!query || !query.trim()) return locations;
  const q = query.toLowerCase().trim();
  return locations.filter((loc) => {
    return (
      loc.currentName.toLowerCase().includes(q) ||
      loc.formerDistrictName.toLowerCase().includes(q) ||
      loc.provinceName.toLowerCase().includes(q) ||
      loc.aliases.some((alias) => alias.toLowerCase().includes(q))
    );
  });
}
